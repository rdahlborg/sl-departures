"""Generate main/metro_data.c from order.json (see routes.py and order.py).

Each route is ordered so trains with SL direction_code 2 travel towards
higher indices, i.e. left to right on the map.
"""
import json, sys, collections

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src))
canon = {int(k): v for k, v in d['canon'].items()}
order = {k: v for k, v in d['order'].items()}
NAMES = {9116: 'S:t Eriksplan'}  # SL's own signage

GROUPS = [
    ('Gröna linjen', 0x179C4C, ['19', '17', '18']),
    ('Röda linjen',  0xD71D24, ['13', '14']),
    ('Blå linjen',   0x0089CA, ['10', '11']),
]

def route(line):
    seqs = [order[f'{line}/2'], list(reversed(order[f'{line}/1']))]
    succ = collections.defaultdict(set); nodes = set()
    for s in seqs:
        nodes |= set(s)
        for a, b in zip(s, s[1:]): succ[a].add(b)
    def reach(n, seen):
        for m in succ[n]:
            if m not in seen: seen.add(m); reach(m, seen)
        return seen
    r = sorted(nodes, key=lambda n: -len(reach(n, set())))
    assert all(r.index(a) < r.index(b) for s in seqs for a, b in zip(s, s[1:])), line
    return r

name = lambda s: NAMES.get(s, canon[s])
out = ['/* Generated by tools/gen_metro_data.py from live SL data. Do not edit. */',
       '#include "metro_data.h"', '']
used = set()
for gi, (gname, color, lines) in enumerate(GROUPS):
    routes = [(l, route(l)) for l in lines]
    picker = []
    for _, r in routes:
        picker += [s for s in r if s not in picker]
    for l, r in routes:
        used |= set(r)
        out.append(f'static const uint16_t route_{l}[] = {{ {", ".join(map(str, r))} }};')
    out.append(f'static const metro_route_t routes_{gi}[] = {{')
    for l, r in routes:
        out.append(f'    {{ {l}, {len(r)}, route_{l} }},   /* {name(r[0])} – {name(r[-1])} */')
    out.append('};')
    out.append(f'static const uint16_t stations_{gi}[] = {{ {", ".join(map(str, picker))} }};')
    out.append('')
out.append('const metro_group_t metro_groups[METRO_N_GROUPS] = {')
for gi, (gname, color, lines) in enumerate(GROUPS):
    picker_len = len(set(s for l in lines for s in route(l)))
    out.append(f'    {{ "{gname}", 0x{color:06X}, {len(lines)}, routes_{gi}, {picker_len}, stations_{gi} }},')
out.append('};')
out.append('')
out.append('static const metro_station_t stations[] = {')
for s in sorted(used):
    out.append(f'    {{ {s}, "{name(s)}" }},')
out.append('};')
out.append('''
const char *metro_station_name(uint16_t site)
{
    for (size_t i = 0; i < sizeof(stations) / sizeof(stations[0]); i++) {
        if (stations[i].site == site) {
            return stations[i].name;
        }
    }
    return "?";
}''')
open(dst, 'w').write('\n'.join(out) + '\n')
print('stations', len(used))
